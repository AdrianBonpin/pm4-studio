/**
 * A Draft is an editable NDEF message with no Tag attached to it — the object a
 * user composes before they have a tag in hand. It is stored by the Rust library
 * store in the same versioned JSON file as Snapshots (see
 * `src-tauri/src/library.rs`), but in its own collection: a Snapshot is a record
 * of a read and is never edited, a Draft is edited constantly and records no Tag.
 *
 * The persistence itself is tested in Rust against a real temp directory. This
 * module is the shape the webview sees plus the pure formatting the Drafts page
 * needs. The encoded size comes from `./ndef`, which owns the codec.
 */

import { recordsByteLength } from "./ndef";

/** The fields one Text Record carries. */
export interface TextRecordFields {
  /** IANA language tag, e.g. "en". Encoded into the Text Record status byte. */
  language: string;
  text: string;
}

/** The fields one URL Record carries: the whole URI, abbreviation included. */
export interface UrlRecordFields {
  url: string;
}

/**
 * One Record in a Draft. The set is deliberately open at the edges: the encoder
 * in `./ndef` is the only thing that decides how a kind is written, so a Record
 * type this build does not know about is still preserved rather than dropped.
 */
export type DraftRecord =
  | { kind: "text"; fields: TextRecordFields }
  | { kind: "url"; fields: UrlRecordFields };

export interface Draft {
  /** Stable across restarts; generated by the store when the Draft is created. */
  id: string;
  name: string;
  /** ISO timestamp of the last edit, written whenever the Draft is saved. */
  updatedAt: string;
  records: DraftRecord[];
}

export interface DraftsView {
  drafts: Draft[];
  /** Set when the library file must not be written to; nothing may be saved. */
  problem: import("./library").LibraryProblem | null;
}

/** Shown in the Drafts section header, so an empty list is not a blank screen. */
export const EMPTY_DRAFTS_TITLE = "No Drafts yet";

export const EMPTY_DRAFTS_DETAIL =
  "A Draft is an NDEF message you are still composing: a list of Records, in order, with no Tag attached. Create one to prepare what a Tag should hold before you have the Tag in hand. Drafts stay here after you quit.";

/** Shown when a Draft exists but holds nothing yet. */
export const EMPTY_DRAFT_TITLE = "This Draft holds no Records";

export const EMPTY_DRAFT_DETAIL =
  "Add a Record to say what the message should contain: a piece of text, or a URL that a phone will offer to open. A Draft belongs to no Tag — its Records are only written to a Tag when you write the whole message.";

/** What a Draft is, said once, wherever the page risks implying otherwise. */
export const DRAFT_NOT_A_TAG_NOTICE =
  "A Draft is not attached to any Tag. Writing one replaces a Tag's whole message rather than adding to it.";

export function draftTitle(draft: Draft): string {
  const name = draft.name.trim();
  return name.length > 0 ? name : draft.id;
}

/** One line of supporting fact: how much is in the Draft and when it changed. */
export function draftDetail(draft: Draft, now: number = Date.now()): string {
  const count = draft.records.length;
  const parts = [
    `${count} ${count === 1 ? "Record" : "Records"}`,
    `${recordsByteLength(draft.records)} bytes`,
  ];
  const when = formatUpdatedAt(draft.updatedAt, now);
  if (when) parts.push(when);
  return parts.join(" · ");
}

/** The Record kind as the user sees it. */
export function recordKindLabel(record: DraftRecord): string {
  switch (record.kind) {
    case "text":
      return "Text";
    case "url":
      return "URL";
  }
}

/** The value the user typed, shortened for a one-line list row. */
export function recordSummary(record: DraftRecord): string {
  switch (record.kind) {
    case "text":
      return record.fields.text;
    case "url":
      return record.fields.url;
  }
}

export function newTextRecord(language = "en", text = ""): DraftRecord {
  return { kind: "text", fields: { language, text } };
}

export function newUrlRecord(url = ""): DraftRecord {
  return { kind: "url", fields: { url } };
}

/**
 * Compact updated-at label, matching how a Snapshot says when it was read: the
 * time is never rounded away entirely.
 */
export function formatUpdatedAt(iso: string, now: number = Date.now()): string {
  const then = new Date(iso).getTime();
  if (Number.isNaN(then)) return "";
  const mins = Math.floor((now - then) / 60_000);
  if (mins < 1) return "just now";
  if (mins < 60) return `${mins}m ago`;
  const hours = Math.floor(mins / 60);
  if (hours < 24) return `${hours}h ago`;
  const days = Math.floor(hours / 24);
  if (days < 7) return `${days}d ago`;
  return new Date(iso).toLocaleDateString(undefined, { day: "numeric", month: "short" });
}
