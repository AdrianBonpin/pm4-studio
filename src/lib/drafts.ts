export const DRAFT_NOT_A_TAG_NOTICE =
  "A Draft is not attached to any Tag. Writing one replaces a Tag's whole message rather than adding to it.";

export function draftTitle(draft: Draft): string {
  const name = draft.name.trim();
  return name.length > 0 ? name : draft.id;
}

/** One line of supporting fact: how much is in the Draft and when it changed. */
export function draftDetail(draft: Draft, now: number = Date.now()): string {
  const count = draft.records.length;
  const parts = [
    `${count} ${count === 1 ? "Record" : "Records"}`,
    encodedTotal(draft.records),
  ];
  const when = formatUpdatedAt(draft.updatedAt, now);
  if (when) parts.push(when);
  return parts.join(" · ");
}

/**
 * The encoded total, or the honest admission that one Record cannot be
 * encoded yet. A malformed field must not turn the Draft list blank.
 */
function encodedTotal(records: readonly DraftRecord[]): string {
  try {
    return `${recordsByteLength(records)} bytes`;
  } catch {
    return "size unavailable";
  }
}

/**
 * How the Draft's total relates to a target capacity. A Draft belongs to no
 * Tag, so callers pass null until a Tag is in hand; the absence is stated
 * rather than filled with a guessed number, because capacity decides whether a
 * write would fit. Where a Tag's capacity is known, the total is compared.
 */
export function capacityNote(byteLength: number, capacityBytes: number | null): string {
  if (capacityBytes === null) {
    return `Target capacity is not known, so ${byteLength} bytes is not compared against it`;
  }
  const remaining = capacityBytes - byteLength;
  if (remaining < 0) return `${byteLength} bytes does not fit in ${capacityBytes}`;
  if (remaining === 0) return `${byteLength} of ${capacityBytes} bytes, full`;
  return `${byteLength} of ${capacityBytes} bytes, ${remaining} left`;
}

/** The Record kind as the user sees it. */
export function recordKindLabel(record: DraftRecord): string {
  switch (record.kind) {
    case "text":
      return RECORD_KIND_LABELS.text;
    case "url":
      return RECORD_KIND_LABELS.url;
    case "phone":
      return RECORD_KIND_LABELS.phone;
    case "email":
      return RECORD_KIND_LABELS.email;
    case "contact":
      return RECORD_KIND_LABELS.contact;
    case "sms":
      return RECORD_KIND_LABELS.sms;
    case "location":
      return RECORD_KIND_LABELS.location;
    case "wifi":
      return RECORD_KIND_LABELS.wifi;
    case "bluetooth":
      return RECORD_KIND_LABELS.bluetooth;
    case "mime":
      return RECORD_KIND_LABELS.mime;
    case "external":
      return RECORD_KIND_LABELS.external;
    default: {
      // A Draft written by a newer build may hold a kind this one cannot name.
      const kind = (record as { kind?: string }).kind ?? "unknown";
      return kind;
    }
  }
}

/** The value the user typed, shortened for a one-line list row. */
export function recordSummary(record: DraftRecord): string {
  switch (record.kind) {
    case "text":
      return record.fields.text;
    case "url":
      return record.fields.url;
    case "phone":
      return record.fields.number;
    case "email":
      return record.fields.address;
    case "contact":
      return record.fields.name;
    case "sms":
      return record.fields.message
        ? `${record.fields.number}: ${record.fields.message}`
        : record.fields.number;
    case "location":
      return `${record.fields.latitude}, ${record.fields.longitude}`;
    case "wifi":
      return record.fields.ssid;
    case "bluetooth":
      return record.fields.address;
    case "mime":
    case "external":
      return record.fields.type;
    default:
      return "";
  }
}

export function newTextRecord(language = "en", text = ""): DraftRecord {
  return { kind: "text", fields: { language, text } };
}

export function newUrlRecord(url = ""): DraftRecord {
  return { kind: "url", fields: { url } };
}

export function newPhoneRecord(number = ""): DraftRecord {
  return { kind: "phone", fields: { number } };
}

export function newEmailRecord(address = ""): DraftRecord {
  return { kind: "email", fields: { address } };
}

export function newContactRecord(fields: Partial<ContactRecordFields> = {}): DraftRecord {
  return {
    kind: "contact",
    fields: { name: "", organization: "", phone: "", email: "", ...fields },
  };
}

export function newSmsRecord(number = "", message = ""): DraftRecord {
  return { kind: "sms", fields: { number, message } };
}

export function newLocationRecord(latitude = "", longitude = ""): DraftRecord {
  return { kind: "location", fields: { latitude, longitude } };
}

export function newWifiRecord(fields: Partial<WifiRecordFields> = {}): DraftRecord {
  return {
    kind: "wifi",
    fields: { ssid: "", networkKey: "", auth: "wpa2-personal", encryption: "aes", ...fields },
  };
}

export function newBluetoothRecord(address = ""): DraftRecord {
  return { kind: "bluetooth", fields: { address } };
}

export function newMimeRecord(type = "text/plain", payloadHex = ""): DraftRecord {
  return { kind: "mime", fields: { type, payloadHex } };
}

export function newExternalRecord(type = "example.com:record", payloadHex = ""): DraftRecord {
  return { kind: "external", fields: { type, payloadHex } };
}

/** A blank Record of any offered kind. */
export function newRecord(kind: RecordKind): DraftRecord {
  switch (kind) {
    case "text":
      return newTextRecord();
    case "url":
      return newUrlRecord();
    case "phone":
      return newPhoneRecord();
    case "email":
      return newEmailRecord();
    case "contact":
      return newContactRecord();
    case "sms":
      return newSmsRecord();
    case "location":
      return newLocationRecord();
    case "wifi":
      return newWifiRecord();
    case "bluetooth":
      return newBluetoothRecord();
    case "mime":
      return newMimeRecord();
    case "external":
      return newExternalRecord();
  }
}

/**
 * Compact updated-at label, matching how a Snapshot says when it was read: the
 * time is never rounded away entirely.
 */
export function formatUpdatedAt(iso: string, now: number = Date.now()): string {
  const then = new Date(iso).getTime();
  if (Number.isNaN(then)) return "";
  const mins = Math.floor((now - then) / 60_000);
  if (mins < 1) return "just now";
  if (mins < 60) return `${mins}m ago`;
  const hours = Math.floor(mins / 60);
  if (hours < 24) return `${hours}h ago`;
  const days = Math.floor(hours / 24);
  if (days < 7) return `${days}d ago`;
  return new Date(iso).toLocaleDateString(undefined, { day: "numeric", month: "short" });
}
