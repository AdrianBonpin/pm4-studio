/**
 * A Draft is an editable NDEF message with no Tag attached to it — the object a
 * user composes before they have a tag in hand. It is stored by the Rust library
 * store in the same versioned JSON file as Snapshots (see
 * `src-tauri/src/library.rs`), but in its own collection: a Snapshot is a record
 * of a read and is never edited, a Draft is edited constantly and records no Tag.
 *
 * The persistence itself is tested in Rust against a real temp directory. This
 * module is the shape the webview sees plus the pure formatting the Drafts page
 * needs. The encoded size comes from `./ndef`, which owns the codec.
 */

import { recordsByteLength } from "./ndef";

/** The fields one Text Record carries. */
export interface TextRecordFields {
  /** IANA language tag, e.g. "en". Encoded into the Text Record status byte. */
  language: string;
  text: string;
}

/** The fields one URL Record carries: the whole URI, abbreviation included. */
export interface UrlRecordFields {
  url: string;
}

/** A phone number, kept as typed; encoded to a canonical `tel:` URI. */
export interface PhoneRecordFields {
  number: string;
}

/** An email address, encoded as a `mailto:` URI. */
export interface EmailRecordFields {
  address: string;
}

/** A contact card, carried as a vCard 3.0 body (`text/vcard`). */
export interface ContactRecordFields {
  name: string;
  organization: string;
  phone: string;
  email: string;
}

/** A text message, carried as an `sms:` URI with an optional body. */
export interface SmsRecordFields {
  number: string;
  message: string;
}

/** A point on Earth, carried as a `geo:` URI. */
export interface LocationRecordFields {
  latitude: string;
  longitude: string;
}

/** The Wi-Fi authentication types this editor offers. */
export type WifiAuth = "open" | "wpa-personal" | "wpa2-personal";

/** The Wi-Fi encryption types that pair with those authentication types. */
export type WifiEncryption = "none" | "tkip" | "aes";

/**
 * WLAN credentials, carried as a Wi-Fi Simple Configuration Configuration
 * Token (`application/vnd.wfa.wsc`). The SSID and key are kept as typed; the
 * encoder owns the canonical bytes.
 */
export interface WifiRecordFields {
  ssid: string;
  networkKey: string;
  auth: WifiAuth;
  encryption: WifiEncryption;
}

/** A Bluetooth device address, carried in a Secure Simple Pairing OOB record. */
export interface BluetoothRecordFields {
  address: string;
}

/** A generic MIME Record: a media type and an arbitrary byte payload as hex. */
export interface MimeRecordFields {
  type: string;
  payloadHex: string;
}

/** An external-type Record: the NDEF external type plus arbitrary bytes as hex. */
export interface ExternalRecordFields {
  type: string;
  payloadHex: string;
}

/**
 * One Record in a Draft. The set is deliberately open at the edges: the encoder
 * in `./ndef` is the only thing that decides how a kind is written, so a Record
 * type this build does not know about is still preserved rather than dropped.
 */
export type DraftRecord =
  | { kind: "text"; fields: TextRecordFields }
  | { kind: "url"; fields: UrlRecordFields }
  | { kind: "phone"; fields: PhoneRecordFields }
  | { kind: "email"; fields: EmailRecordFields }
  | { kind: "contact"; fields: ContactRecordFields }
  | { kind: "sms"; fields: SmsRecordFields }
  | { kind: "location"; fields: LocationRecordFields }
  | { kind: "wifi"; fields: WifiRecordFields }
  | { kind: "bluetooth"; fields: BluetoothRecordFields }
  | { kind: "mime"; fields: MimeRecordFields }
  | { kind: "external"; fields: ExternalRecordFields };

/** A Record kind this build can author. */
export type RecordKind = DraftRecord["kind"];

/**
 * The Record types the editor offers, in order. Fixed by the specification's
 * answer to its record-set question: types that only mean something to a phone
 * app (an Android application launch, a social profile deep link, HomeKit, a
 * payment link, a 3D printer) are deliberately absent. Adding one here means
 * expanding that decision, not just adding a form.
 */
export const RECORD_KINDS: readonly RecordKind[] = [
  "text",
  "url",
  "phone",
  "email",
  "contact",
  "sms",
  "location",
  "wifi",
  "bluetooth",
  "mime",
  "external",
];

export const RECORD_KIND_LABELS: Record<RecordKind, string> = {
  text: "Text",
  url: "URL",
  phone: "Phone",
  email: "Email",
  contact: "Contact",
  sms: "SMS",
  location: "Location",
  wifi: "Wi-Fi",
  bluetooth: "Bluetooth",
  mime: "MIME",
  external: "External",
};

export interface Draft {
  /** Stable across restarts; generated by the store when the Draft is created. */
  id: string;
  name: string;
  /** ISO timestamp of the last edit, written whenever the Draft is saved. */
  updatedAt: string;
  records: DraftRecord[];
}

export interface DraftsView {
  drafts: Draft[];
  /** Set when the library file must not be written to; nothing may be saved. */
  problem: import("./library").LibraryProblem | null;
  /**
   * Set when a file written by an older schema was lifted but the lift could
   * not be written back. The Drafts here are whole and saving is allowed, so
   * this is a warning rather than a lock.
   */
  migrationWarning: string | null;
}

